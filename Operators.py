#Addition
x = 5
y = 10
z = x + y
print(z)

#subtraction
x = 10
y = 5
z = x - y
print(z)

#Multiplication
x = 5
y = 10
z = x * y
print(z)

#Division
x = 10
y = 5
z = x / y
print(z)


#Modulus
x = 10
y = 3
z = x % y
print(z)  # Modulus will return the remainder of the division, which is 1 in this case.

#Exponents
x = 2
y = 3
z = x ** y # use the double asterisk (**) operator to calculate the exponentiation, which raises x to the power of y.
print(z)  # Exponents will return the result of raising x to the power of y, which is 8 in this case.