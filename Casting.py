#casting
#example of casting in python 1
x = int(1)   # x will be 1
y = int(2.8) # y will be 2
z = int("3") # z will be 3

#example of casting in python 2
x = float(1)     # x will be 1.0
y = float(2.8)   # y will be 2.8
z = float("3")   # z will be 3.0

#example of casting in python 3
x = str(1)     # x will be "1"
y = str(2.8)   # y will be "2.8"
z = str("3")   # z will be "3"

