#Booleans
#True=1
#False=0
print(10 > 9)  # This will print True because 10 is greater than 9.
print(10 == 9)  # This will print False because 10 is not equal to 9.
print(10 < 9)  # This will print False because 10 is not less than 9.

#Boolean Values
a = True
b = False
print(a)  # This will print True.
print(b)  # This will print False.

#Evaluate Values and Variables
print(bool("Hello"))  # This will print True because a non-empty string is considered True.
print(bool(15))  # This will print True because a non-zero number is considered True.
print(bool([]))  # This will print False because an empty list is considered False.
print(bool(""))  # This will print False because an empty string is considered False.

#And operator
print(True and True)  # This will print True because both values are True.
print(True and False)  # This will print False because not all values are True.
print(False and False)  # This will print False because not all values are True.

#Or operator
print(True or False)  # This will print True because at least one value is True.
print(False or False)  # This will print False because none of the values are True.

#Not operator
print(not True)  # This will print False because not True is False.
print(not False)  # This will print True because not False is True.

